#!/usr/bin/env node
/**
 * Builds the Voygo Android APK (Capacitor WebView shell around the deployed site).
 *
 *   npm run android:apk -- https://your-app.vercel.app
 *
 * The URL can also come from the VOYGO_APP_URL env var. Without one, the APK
 * shows a "not configured" page. Output: dist/voygo-debug.apk (debug-signed,
 * installable by sideloading).
 */
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { homedir, platform } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const isWin = platform() === "win32";

function fail(msg) {
  console.error(`\n✖ ${msg}\n`);
  process.exit(1);
}

// ── Server URL ──────────────────────────────────────────────────────────────
const rawUrl = (process.argv[2] ?? process.env.VOYGO_APP_URL ?? "").trim().replace(/\/+$/, "");
let appUrl = null;
if (rawUrl) {
  let parsed;
  try {
    parsed = new URL(rawUrl);
  } catch {
    fail(`Not a valid URL: ${rawUrl}`);
  }
  const local = ["localhost", "127.0.0.1"].includes(parsed.hostname);
  // Geolocation and secure cookies need HTTPS; plain http only for USB testing via `adb reverse`.
  if (parsed.protocol !== "https:" && !local) fail(`Use an https:// URL (got ${rawUrl}).`);
  appUrl = parsed.origin + (parsed.pathname === "/" ? "" : parsed.pathname);
}
console.log(appUrl ? `→ APK will load ${appUrl}` : "→ No URL given: APK will show the 'not configured' page");

writeFileSync(
  join(root, "capacitor/www/app-url.js"),
  `// Generated by scripts/build-apk.mjs — the server URL this APK loads.\nwindow.VOYGO_APP_URL = ${JSON.stringify(appUrl)};\n`
);

// ── Toolchain: JDK (Android Studio bundles one) + Android SDK ────────────────
const env = { ...process.env, VOYGO_APP_URL: appUrl ?? "" };

const javaBin = (home) => join(home, "bin", isWin ? "java.exe" : "java");
if (!env.JAVA_HOME || !existsSync(javaBin(env.JAVA_HOME))) {
  const candidates = isWin
    ? ["C:\\Program Files\\Android\\Android Studio\\jbr", join(env.LOCALAPPDATA ?? "", "Programs", "Android Studio", "jbr")]
    : ["/Applications/Android Studio.app/Contents/jbr/Contents/Home", "/opt/android-studio/jbr", join(homedir(), "android-studio", "jbr")];
  const jbr = candidates.find((p) => existsSync(javaBin(p)));
  if (!jbr) fail("No JDK found. Install Android Studio or set JAVA_HOME to a JDK 21.");
  env.JAVA_HOME = jbr;
  console.log(`→ Using JDK at ${jbr}`);
}

if (!env.ANDROID_HOME && !env.ANDROID_SDK_ROOT) {
  const sdk = isWin
    ? join(env.LOCALAPPDATA ?? "", "Android", "Sdk")
    : join(homedir(), platform() === "darwin" ? "Library/Android/sdk" : "Android/Sdk");
  if (!existsSync(sdk)) fail("Android SDK not found. Install it via Android Studio or set ANDROID_HOME.");
  env.ANDROID_HOME = sdk;
}

function run(cmd, cwd) {
  console.log(`\n$ ${cmd}`);
  // shell: true is required on Windows to run .bat/.cmd files (npx, gradlew.bat).
  const res = spawnSync(cmd, { cwd, env, stdio: "inherit", shell: true });
  if (res.status !== 0) fail(`Command failed: ${cmd}`);
}

// ── Build ───────────────────────────────────────────────────────────────────
run("npx cap sync android", root);
// Explicit ./ path: cmd.exe may be configured not to search the current dir.
run(`${isWin ? ".\\gradlew.bat" : "./gradlew"} assembleDebug`, join(root, "android"));

const built = join(root, "android/app/build/outputs/apk/debug/app-debug.apk");
if (!existsSync(built)) fail(`Gradle finished but ${built} is missing.`);
mkdirSync(join(root, "dist"), { recursive: true });
const out = join(root, "dist/voygo-debug.apk");
copyFileSync(built, out);

// Also stage it as a download on the site (gitignored; shipped by `vercel deploy`).
// Only for builds that point at a server — the unconfigured APK is useless to share.
if (appUrl) {
  const downloads = join(root, "public/downloads");
  mkdirSync(downloads, { recursive: true });
  copyFileSync(built, join(downloads, "voygo.apk"));
}

console.log(`\n✔ APK ready: ${out}`);
if (appUrl) console.log(`  After \`vercel deploy --prod\`, phones can download it from ${appUrl}/downloads/voygo.apk`);
console.log(`  Or install on a USB-connected phone: adb install -r "${out}"\n`);
